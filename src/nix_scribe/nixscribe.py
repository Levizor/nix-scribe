import datetime
import logging
import os
import platform
import time
from collections import defaultdict
from pathlib import Path

from rich import box
from rich.console import Console
from rich.panel import Panel
from rich.progress import (
    BarColumn,
    MofNCompleteColumn,
    Progress,
    SpinnerColumn,
    TextColumn,
    TimeElapsedColumn,
)
from rich.table import Table
from rich.tree import Tree

from nix_scribe.cli.arguments import args, confirm
from nix_scribe.lib.context import ElevationRequest, SystemContext
from nix_scribe.lib.emitter import emit_nix_fragment
from nix_scribe.lib.ir_serializer import save_ir_to_file
from nix_scribe.lib.modularization import ModularizationLevel
from nix_scribe.lib.nix_fragment import NixFragment
from nix_scribe.lib.nix_module import NixModule
from nix_scribe.lib.nixfile import NixFile
from nix_scribe.lib.registry import Scanner
from nix_scribe.lib.scheduler import ScannerScheduler

logger = logging.getLogger(__name__)


class NixScribe:
    def __init__(self, console: Console, modules: dict[str, Scanner]):
        self.context = SystemContext(args.root_path, use_sudo=os.geteuid() == 0)
        self.root_file = NixFile("configuration", "Generated by nix-scribe")
        self.modules = ScannerScheduler.schedule(modules)
        self.results: dict[str, NixModule | None] = dict.fromkeys(self.modules)
        self.fragments: dict[str, NixFragment | None] = dict.fromkeys(self.modules)
        self.console = console

    def run(self):
        """
        Top level script.
        Scans system and writes configuration.
        """
        overall_start = time.perf_counter()
        logger.debug(datetime.datetime.now())
        logger.info("Starting nix-scribe system scan...")

        scan_start = time.perf_counter()
        with Progress(
            SpinnerColumn(),
            TextColumn("[progress.description]{task.description}"),
            BarColumn(),
            MofNCompleteColumn(),
            TimeElapsedColumn(),
            console=self.console,
            transient=True,
        ) as progress:
            scan_task = progress.add_task(
                "[bold cyan]Scanning system[/]", total=len(self.modules)
            )
            for scanner in self.modules.values():
                progress.update(
                    scan_task,
                    description=f"[bold cyan]Scanning system[/] [dim]({scanner.name})[/]",
                )
                self._scan_module(scanner, progress=progress)
                progress.advance(scan_task)

        total_modules = len(self.modules)
        scan_duration = time.perf_counter() - scan_start
        configured_modules = sum(1 for f in self.fragments.values() if f is not None)
        logger.info(
            "Finished system scan in %.2fs (%d scanned, %d configured, %d skipped)",
            scan_duration,
            total_modules,
            configured_modules,
            total_modules - configured_modules,
        )

        logger.info("Writing configuration...")
        self._assemble_config(mod_level=args.modularization)
        self.root_file.save(args.output_path, args.modularization)

        if args.dump_ir:
            ir_file = save_ir_to_file(self.results, args.output_path)
            logger.info("Saved scanned IR to %s", ir_file)

        logger.info(f"Done. Saved configuration to {args.output_path}")
        self._print_summary(total_duration=time.perf_counter() - overall_start)

    def _print_summary(self, total_duration: float) -> None:
        """Renders end-of-run execution summary panel."""
        grid = Table.grid(padding=(0, 2))
        grid.add_column(style="bold cyan")
        grid.add_column()

        os_info = self.context.os_info
        pretty_name = os_info.get("PRETTY_NAME") or os_info.get("NAME")
        version = os_info.get("VERSION_ID") or os_info.get("VERSION")
        arch = platform.machine()
        if pretty_name:
            version_str = (
                f" {version}" if version and version not in pretty_name else ""
            )
            os_display = f"{pretty_name}{version_str} ({arch})"
        else:
            os_display = arch

        pm_name = (
            self.context.package_manager.name
            if self.context.package_manager
            else "[dim]None detected[/dim]"
        )

        grid.add_row("Target OS:", os_display)
        grid.add_row("Target Root:", str(self.context.root))
        grid.add_row("Package Manager:", pm_name)
        grid.add_row("Elapsed Time:", f"{total_duration:.2f}s")

        grid.add_row("", "")

        configured = [name for name, f in self.fragments.items() if f is not None]
        skipped = [name for name, f in self.fragments.items() if f is None]

        grid.add_row("Modules:", self._build_modules_tree(configured))

        if skipped:
            grid.add_row(
                "", f"[dim]{len(skipped)} skipped (no configuration detected)[/dim]"
            )

        pkg_state = self.context._packages
        if pkg_state is not None and (pkg_state.resolved or pkg_state.unmapped):
            grid.add_row("", "")
            explicit = sum(1 for p in pkg_state.resolved if p.is_explicit)
            preinstalled = sum(1 for p in pkg_state.resolved if p.is_preinstalled)
            pkg_summary = (
                f"{len(pkg_state.resolved)} resolved "
                f"([dim]{explicit} explicit, {preinstalled} preinstalled[/dim]) • "
                f"{len(pkg_state.claimed)} claimed • "
                f"{len(pkg_state.unmapped)} unmapped"
            )
            grid.add_row("Packages:", pkg_summary)

        artifacts: list[str] = []
        if args.output_path.exists():
            for p in sorted(args.output_path.rglob("*")):
                if p.is_file():
                    artifacts.append(str(p.relative_to(args.output_path)))
        if args.log_file and args.log_file.exists():
            try:
                args.log_file.relative_to(args.output_path)
            except ValueError:
                artifacts.append(str(args.log_file))

        if artifacts:
            grid.add_row("", "")
            grid.add_row("Artifacts:", self._build_artifacts_tree(artifacts))

        panel = Panel(
            grid,
            title="[bold green]✓ nix-scribe generation complete[/bold green]",
            border_style="green",
            box=box.ROUNDED,
        )
        self.console.print(panel)

    def _build_artifacts_tree(self, artifact_paths: list[str]) -> Tree | str:
        """Builds a hierarchical tree representation of generated artifacts."""
        if not artifact_paths:
            return "[dim]None[/dim]"

        tree = Tree(
            f"[bold]{len(artifact_paths)} files generated[/bold]",
            guide_style="dim",
        )
        nodes: dict[str, Tree] = {}

        for path_str in sorted(artifact_paths):
            parts = Path(path_str).parts
            curr = tree
            for i in range(len(parts) - 1):
                dir_path = "/".join(parts[: i + 1])
                if dir_path not in nodes:
                    nodes[dir_path] = curr.add(f"[bold blue]{parts[i]}[/bold blue]")
                curr = nodes[dir_path]

            curr.add(parts[-1])

        return tree

    def _build_modules_tree(self, configured_names: list[str]) -> Tree | str:
        """Builds a hierarchical tree representation of configured module paths."""
        if not configured_names:
            return "[yellow]0 configured[/yellow]"

        tree = Tree(
            f"[bold green]{len(configured_names)} configured[/bold green]",
            guide_style="dim",
        )
        nodes: dict[str, Tree] = {}
        configured_set = set(configured_names)

        for name in sorted(configured_names):
            parts = name.split(".")
            curr = tree
            for i in range(len(parts) - 1):
                path = ".".join(parts[: i + 1])
                if path not in nodes:
                    style = "bold blue" if path not in configured_set else "green"
                    nodes[path] = curr.add(f"[{style}]{parts[i]}[/{style}]")
                curr = nodes[path]

            full_path = name
            if full_path not in nodes:
                node = curr.add(f"[green]{parts[-1]}[/green]")
                nodes[full_path] = node

        return tree

    def _assemble_config(self, mod_level: ModularizationLevel) -> None:
        categories: dict[str, list[str]] = defaultdict(
            list
        )  # networking -> [networking.networkmanager, networking.firewall]
        for module_name in self.modules.keys():
            categories[module_name.split(".")[0]].append(module_name)

        for category in categories:
            module_names = categories[category]
            if not module_names:
                continue
            option_file = NixFile(category, f"{category} configuration")
            for module_name in module_names:
                fragment = self.fragments[module_name]
                if fragment:
                    if args.modularization == ModularizationLevel.COMPONENT_LEVEL:
                        component_file = NixFile(fragment.name)
                        component_file.add_fragment(fragment)
                        option_file.add_import(component_file)
                    elif args.modularization == ModularizationLevel.HIGH_LEVEL:
                        option_file.add_fragment(fragment)
                    elif args.modularization == ModularizationLevel.SINGLE_FILE:
                        self.root_file.add_fragment(fragment)

            if args.modularization != ModularizationLevel.SINGLE_FILE and (
                any(option_file.imports) or any(option_file.document._index)
            ):
                self.root_file.add_import(option_file)

    def _scan_module(self, mod: Scanner, progress: Progress | None = None):
        """
        Runs a scanner, handling permission requests
        """
        while True:
            try:
                if not mod.scan:
                    logger.warning(f"Module {mod.name} has no scanner.")
                    return

                scan_data = mod.scan(self.context)
                logger.debug(f"Scanned {mod.name}")
                if isinstance(scan_data, NixModule):
                    fragment = emit_nix_fragment(
                        scan_data,
                        name=mod.name.split(".")[-1],
                        description=mod.description,
                        prefix=scan_data.prefix,
                    )
                    if not fragment:
                        self.results[mod.name] = None
                        self.fragments[mod.name] = None
                        logger.debug(
                            f"Module {mod.name} yielded no configured options; skipping."
                        )
                    else:
                        self.results[mod.name] = scan_data
                        self.fragments[mod.name] = fragment
                        self.context.packages.claim(
                            *scan_data.resolve_claims(), by=mod.name
                        )
                else:
                    self.results[mod.name] = scan_data
                    self.fragments[mod.name] = None
                break
            except ElevationRequest as e:
                logger.warning(f"Permission denied: {e.description}")

                if self.context.use_sudo:
                    logger.error(
                        "Sudo was attempted, but failed (authentication or access failure). Skipping."
                    )
                    return

                if progress is not None:
                    progress.stop()

                retry_with_sudo = self._prompt_for_sudo()

                if progress is not None:
                    progress.start()

                if retry_with_sudo:
                    if self.context.verify_sudo():
                        logger.info("Sudo privileges acquired!")
                        continue
                    else:
                        logger.warning("Sudo authentication failed. Skipping.")
                        return
                else:
                    logger.warning("Skipping this scanner.")
                    return
            except Exception as e:
                logger.error(f"Failed scanning {mod.name}: {e}")
                return

    def _prompt_for_sudo(self) -> bool:
        try:
            return confirm(
                "[bold yellow]Permission required.[/] Do you want to retry with sudo privileges?",
                console=self.console,
                default=True,
            )
        except EOFError:
            return False
